# Reverse lookup: code -> display name
_CODE_TO_LABEL = {v: k for k, v in AVAILABLE_LANGUAGES.items()}


def t(key: str, **kwargs) -> str:
    """Translate a key to the current language.

    Falls back to English if the key is missing in the selected language.
    """
    try:
        lang = st.session_state.get("language", "en")
    except Exception:
        lang = "en"

    strings = _STRINGS.get(lang, _STRINGS["en"])
    # Fall back to English if key missing in current language
    text = strings.get(key, _STRINGS["en"].get(key, key))

    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass

    return text


def get_current_language() -> str:
    """Get the current language code."""
    try:
        return st.session_state.get("language", "en")
    except Exception:
        return "en"


def get_language_label(code: str) -> str:
    """Get display name for a language code."""
    return _CODE_TO_LABEL.get(code, "English")


def set_language(lang_code: str):
    """Set the current language."""
    if lang_code in _STRINGS:
        st.session_state["language"] = lang_code
